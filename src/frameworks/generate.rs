// src/frameworks/generate.rs
//
// The shared template → RustSploit module generator.
//
// One generator for every framework the bridge layer understands. What it
// emits is not a stub that needs hand-editing before it compiles:
//
//   * the **source template is embedded verbatim** and executed through the
//     bridge engine, so a generated module behaves exactly like the template
//     it came from — including its matchers, extractors and variables;
//   * the module is **registered** (`register_native_module!`) and the
//     parent `mod.rs` is updated (`pub mod <name>;`), so it is part of the
//     build the moment it is written — the three-part contract the repo
//     enforces;
//   * the emitted code is **audit-clean**: no `let _ =` swallowing, no
//     panicking constructs, no lint suppression.
//
// A framework whose semantics cannot be reproduced (Metasploit, Empire,
// Cobalt Strike) gets a *scaffold* instead: the metadata, the port default
// and the option prompts, plus a reachability probe — never a fabricated
// "vulnerable" string check.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use super::{Protocol, Template, TemplateOption};

/// What the generator produced.
#[derive(Debug, Clone)]
pub struct GeneratedModule {
    /// Where the module was written.
    pub path: PathBuf,
    /// The generated source.
    pub code: String,
    /// Qualified module name (`category/name`).
    pub qualified_name: String,
    /// Whether the parent `mod.rs` was updated to declare the module.
    pub registered_in_parent: bool,
}

/// Render a Rust string literal, escaping what has to be escaped.
///
/// The template description regularly contains quotes, backslashes and
/// newlines — interpolating those raw into `"{}"` produces a module that does
/// not compile.
pub fn rust_string_literal(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len() + 2);
    out.push('"');
    for c in raw.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if u32::from(c) < 0x20 => {
                out.push_str(&format!("\\u{{{:x}}}", u32::from(c)));
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A raw string literal (`r#"…"#`) that survives any content except the
/// delimiter itself.
pub fn rust_raw_string_literal(raw: &str) -> String {
    let mut hashes = String::new();
    while raw.contains(&format!("\"{hashes}\"")) {
        hashes.push('#');
    }
    format!("r{hashes}\"{raw}\"{hashes}")
}

/// Derive a safe Rust module name from a file stem.
pub fn module_name_from(path: &Path) -> String {
    path.file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("translated_module")
        .replace(['-', ' ', '.'], "_")
        .to_lowercase()
}

/// Generate the RustSploit module source for a template.
///
/// `source` is the original template file, embedded verbatim so the module
/// can re-parse and execute it.
pub fn generate(template: &Template, category: &str, source: &str) -> String {
    match &template.protocol {
        Protocol::Http(_) | Protocol::Dns(_) | Protocol::Tcp(_) => {
            generate_executable(template, category, source)
        }
        Protocol::None => generate_scaffold(template, category),
    }
}

/// A module that executes the embedded template through the bridge engine.
fn generate_executable(template: &Template, category: &str, source: &str) -> String {
    let mut out = String::new();

    out.push_str(&format!(
        "//! {} — translated from a {} template\n",
        template.name, template.framework
    ));
    out.push_str("//!\n");
    if !template.description.is_empty() {
        out.push_str(&format!(
            "//! {}\n",
            template.description.replace('\n', "\n//! ")
        ));
    }
    if !template.authors.is_empty() {
        out.push_str(&format!(
            "//! Original authors: {}\n",
            template.authors.join(", ")
        ));
    }
    out.push_str("//!\n");
    out.push_str(&format!(
        "//! The template is embedded verbatim and executed by the framework bridge\n\
         //! (`crate::frameworks`), so its matchers, extractors and variables behave\n\
         //! exactly as they do in the source framework.\n"
    ));
    out.push_str("//!\n");
    out.push_str("//! Generated by RustSploit — regenerate instead of hand-editing.\n\n");

    out.push_str("use anyhow::{Context, Result};\n\n");
    out.push_str("use crate::frameworks::{ExecutionCtx, Template};\n");
    out.push_str("use crate::module::{Finding, FindingKind, ModuleCtx, ModuleOutcome};\n");
    out.push_str("use crate::module_info::{ModuleInfo, ModuleRank};\n\n");

    out.push_str("/// The source template, embedded verbatim.\n");
    out.push_str(&format!(
        "const TEMPLATE_SOURCE: &str = {};\n\n",
        rust_raw_string_literal(source)
    ));

    // info()
    out.push_str("pub fn info() -> ModuleInfo {\n");
    out.push_str("    ModuleInfo {\n");
    out.push_str(&format!(
        "        name: {}.to_string(),\n",
        rust_string_literal(&template.name)
    ));
    out.push_str(&format!(
        "        description: {}.to_string(),\n",
        rust_string_literal(&format!(
            "{} (translated from a {} template)",
            template.description, template.framework
        ))
    ));
    out.push_str(&format!(
        "        authors: vec![{}],\n",
        template
            .authors
            .iter()
            .map(|a| format!("{}.to_string()", rust_string_literal(a)))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out.push_str(&format!(
        "        references: vec![{}],\n",
        template
            .references
            .iter()
            .map(|r| format!("{}.to_string()", rust_string_literal(r)))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out.push_str("        disclosure_date: None,\n");
    out.push_str(&format!(
        "        rank: ModuleRank::{},\n",
        rank_variant(template.severity.module_rank())
    ));
    out.push_str(&format!(
        "        default_port: Some({}),\n",
        template.default_port.unwrap_or(443)
    ));
    out.push_str("    }\n");
    out.push_str("}\n\n");

    // run()
    out.push_str("pub async fn run(ctx: &ModuleCtx) -> Result<ModuleOutcome> {\n");
    out.push_str("    let target = ctx.target.as_single()\n");
    out.push_str("        .context(\"this module requires a single-host target\")?;\n");
    out.push_str("    let template = Template::from_source(TEMPLATE_SOURCE)\n");
    out.push_str("        .context(\"parse embedded template\")?;\n");
    let port = template.default_port.unwrap_or(443);
    out.push_str(&format!(
        "    let port = crate::utils::cfg_prompt_port(\"port\", \"Target port\", {port}).await?;\n"
    ));
    out.push_str("    let scheme = crate::utils::cfg_prompt_default(\n");
    out.push_str("        \"scheme\",\n");
    out.push_str("        \"Scheme (http/https)\",\n");
    out.push_str(&format!(
        "        \"{}\",\n",
        if port == 80 { "http" } else { "https" }
    ));
    out.push_str("    )\n");
    out.push_str("    .await?;\n");
    out.push_str("    let timeout = crate::utils::cfg_prompt_int_range(\n");
    out.push_str("        \"timeout\",\n");
    out.push_str("        \"Request timeout in seconds\",\n");
    out.push_str("        10,\n");
    out.push_str("        1,\n");
    out.push_str("        300,\n");
    out.push_str("    )\n");
    out.push_str("    .await?;\n\n");
    out.push_str("    let exec = ExecutionCtx {\n");
    out.push_str("        host: target,\n");
    out.push_str("        port,\n");
    out.push_str("        scheme: &scheme,\n");
    out.push_str("        variables: Default::default(),\n");
    out.push_str("        timeout: std::time::Duration::from_secs(timeout as u64),\n"); // audit-allow: emitted source text; generated timeout is clamped to 1..=300
    out.push_str("        insecure: false,\n");
    out.push_str("    };\n\n");
    out.push_str("    let results = template.execute(&exec)?;\n\n");
    out.push_str("    let mut outcome = ModuleOutcome::ok();\n");
    out.push_str("    for result in &results {\n");
    out.push_str("        if !result.matched {\n");
    out.push_str("            continue;\n");
    out.push_str("        }\n");
    out.push_str("        crate::mprintln!(\n");
    out.push_str("            \"{}\",\n");
    out.push_str(
        "            format!(\"[+] {} — {}\", result.severity.as_str(), result.message).green()\n",
    );
    out.push_str("        );\n");
    out.push_str("        outcome.findings.push(Finding {\n");
    out.push_str("            target: target.to_string(),\n");
    out.push_str("            kind: FindingKind::Vulnerable,\n");
    out.push_str("            message: result.message.clone(),\n");
    out.push_str("            data: Some(serde_json::json!({\n");
    out.push_str("                \"severity\": result.severity.as_str(),\n");
    out.push_str("                \"evidence\": result.evidence,\n");
    out.push_str("                \"extracted\": result.extracted,\n");
    out.push_str("            })),\n");
    out.push_str("        });\n");
    out.push_str("    }\n");
    out.push_str("    if outcome.findings.is_empty() {\n");
    out.push_str("        crate::mprintln!(\"{}\", \"[-] template did not match\".yellow());\n");
    out.push_str("    }\n");
    out.push_str("    Ok(outcome)\n");
    out.push_str("}\n\n");

    out.push_str(&registration(
        category,
        &module_name_from(Path::new(&template.name)),
    ));
    out
}

/// A scaffold module for a framework whose body cannot be reproduced.
fn generate_scaffold(template: &Template, category: &str) -> String {
    let mut out = String::new();

    out.push_str(&format!(
        "//! {} — translated from a {} template\n",
        template.name, template.framework
    ));
    out.push_str("//!\n");
    if !template.description.is_empty() {
        out.push_str(&format!(
            "//! {}\n",
            template.description.replace('\n', "\n//! ")
        ));
    }
    if !template.authors.is_empty() {
        out.push_str(&format!(
            "//! Original authors: {}\n",
            template.authors.join(", ")
        ));
    }
    out.push_str("//!\n");
    out.push_str(&format!(
        "//! A {} body is {} — the metadata, the port default and the option\n\
         //! prompts were carried over; the probe below is a reachability check\n\
         //! that you are expected to replace with the real exploit logic.\n",
        template.framework,
        match template.framework.as_str() {
            "msf" => "Ruby that drives the Metasploit transport layer",
            "empire" => "PowerShell executed through an agent",
            "cobaltstrike" => "Squirrel callbacks",
            _ => "not reproducible natively",
        }
    ));
    out.push_str("//!\n");
    out.push_str("//! Generated by RustSploit — regenerate instead of hand-editing.\n\n");

    out.push_str("use anyhow::{Context, Result};\n\n");
    out.push_str("use crate::module::{Finding, FindingKind, ModuleCtx, ModuleOutcome};\n");
    out.push_str("use crate::module_info::{ModuleInfo, ModuleRank};\n\n");

    // info()
    out.push_str("pub fn info() -> ModuleInfo {\n");
    out.push_str("    ModuleInfo {\n");
    out.push_str(&format!(
        "        name: {}.to_string(),\n",
        rust_string_literal(&template.name)
    ));
    out.push_str(&format!(
        "        description: {}.to_string(),\n",
        rust_string_literal(&format!(
            "{} (translated from a {} template)",
            template.description, template.framework
        ))
    ));
    out.push_str(&format!(
        "        authors: vec![{}],\n",
        template
            .authors
            .iter()
            .map(|a| format!("{}.to_string()", rust_string_literal(a)))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out.push_str(&format!(
        "        references: vec![{}],\n",
        template
            .references
            .iter()
            .map(|r| format!("{}.to_string()", rust_string_literal(r)))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out.push_str("        disclosure_date: None,\n");
    out.push_str(&format!(
        "        rank: ModuleRank::{},\n",
        rank_variant(template.severity.module_rank())
    ));
    out.push_str(&format!(
        "        default_port: Some({}),\n",
        template.default_port.unwrap_or(443)
    ));
    out.push_str("    }\n");
    out.push_str("}\n\n");

    // run()
    out.push_str("pub async fn run(ctx: &ModuleCtx) -> Result<ModuleOutcome> {\n");
    out.push_str("    let target = ctx.target.as_single()\n");
    out.push_str("        .context(\"this module requires a single-host target\")?;\n");
    let port = template.default_port.unwrap_or(443);
    out.push_str(&format!(
        "    let port = crate::utils::cfg_prompt_port(\"port\", \"Target port\", {port}).await?;\n"
    ));
    for opt in &template.options {
        out.push_str(&format!(
            "    let {} = crate::utils::cfg_prompt_default(\n",
            rust_ident(&opt.name)
        ));
        out.push_str(&format!("        {},\n", rust_string_literal(&opt.name)));
        out.push_str(&format!(
            "        {},\n",
            rust_string_literal(&opt.description)
        ));
        out.push_str(&format!("        {},\n", rust_string_literal(&opt.default)));
        out.push_str("    )\n");
        out.push_str("    .await?;\n");
    }
    out.push('\n');
    out.push_str("    // ── PROBE ──────────────────────────────────────────────────────\n");
    out.push_str("    // The source framework's exploit body is not reproducible here.\n");
    out.push_str("    // Replace this reachability check with the real exploit logic.\n");
    out.push_str("    let reachable = tokio::net::TcpStream::connect((target, port))\n");
    out.push_str("        .await\n");
    out.push_str("        .is_ok();\n\n");
    out.push_str("    let mut outcome = ModuleOutcome::ok();\n");
    out.push_str("    outcome.findings.push(Finding {\n");
    out.push_str("        target: target.to_string(),\n");
    out.push_str("        kind: FindingKind::Note,\n");
    out.push_str("        message: format!(\n");
    out.push_str("            \"translated from a {} template — port {} {}\",\n");
    out.push_str(&format!(
        "            {},\n",
        rust_string_literal(&template.framework)
    ));
    out.push_str("            port,\n");
    out.push_str("            if reachable { \"reachable\" } else { \"closed\" },\n");
    out.push_str("        ),\n");
    out.push_str("        data: Some(serde_json::json!({\n");
    out.push_str("            \"framework\": ");
    out.push_str(&format!("{},\n", rust_string_literal(&template.framework)));
    out.push_str("            \"port\": port,\n");
    out.push_str("            \"reachable\": reachable,\n");
    out.push_str("        })),\n");
    out.push_str("    });\n");
    out.push_str("    Ok(outcome)\n");
    out.push_str("}\n\n");

    out.push_str(&registration(
        category,
        &module_name_from(Path::new(&template.name)),
    ));
    out
}

/// The `register_native_module!` call for a generated module.
fn registration(category: &str, module_name: &str) -> String {
    let cat_variant = match category {
        "scanners" => "Scanners",
        "creds" => "Creds",
        "plugins" => "Plugins",
        "osint" => "Osint",
        "post" => "Post",
        _ => "Exploits",
    };
    format!(
        "crate::register_native_module!(crate::module::Category::{cat_variant}, \"{module_name}\", native);\n"
    )
}

/// Rust keyword → the `ModuleRank` variant name.
fn rank_variant(rank: crate::module_info::ModuleRank) -> &'static str {
    match rank {
        crate::module_info::ModuleRank::Excellent => "Excellent",
        crate::module_info::ModuleRank::Great => "Great",
        crate::module_info::ModuleRank::Good => "Good",
        crate::module_info::ModuleRank::Normal => "Normal",
        crate::module_info::ModuleRank::Low => "Low",
        crate::module_info::ModuleRank::Manual => "Manual",
    }
}

/// Turn an option name into a usable Rust identifier.
fn rust_ident(name: &str) -> String {
    let mut ident = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_alphanumeric() || c == '_' {
            if i == 0 && c.is_ascii_digit() {
                ident.push('_');
            }
            ident.push(c.to_ascii_lowercase());
        } else {
            ident.push('_');
        }
    }
    if ident.is_empty() {
        return "option".to_string();
    }
    if matches!(
        ident.as_str(),
        "as" | "break"
            | "const"
            | "continue"
            | "crate"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "async"
            | "await"
            | "dyn"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "macro"
            | "override"
            | "priv"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
            | "try"
    ) {
        ident.push('_');
    }
    ident
}

/// Write a generated module to disk and declare it in the parent `mod.rs`.
///
/// The parent declaration is the third part of the repo's module contract
/// (file + `register_native_module!` + `pub mod` in the parent): without it
/// the module compiles away and the operator can never run it.
pub fn write_module(
    template: &Template,
    source: &str,
    output_dir: &Path,
    category: &str,
) -> Result<GeneratedModule> {
    let stem = Path::new(&template.name)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("translated_module")
        .to_string();
    let module_name = module_name_from(&PathBuf::from(stem));
    let code = generate(template, category, source);

    std::fs::create_dir_all(output_dir)
        .with_context(|| format!("create {}", output_dir.display()))?;
    let path = output_dir.join(format!("{module_name}.rs"));
    std::fs::write(&path, &code).with_context(|| format!("write {}", path.display()))?; // audit-allow: synchronous generator, not on an async runtime

    let registered_in_parent = declare_in_parent(output_dir, category, &module_name);

    Ok(GeneratedModule {
        path,
        code,
        qualified_name: format!("{category}/{module_name}"),
        registered_in_parent,
    })
}

/// Add `pub mod <name>;` to the category's `mod.rs` (idempotent).
fn declare_in_parent(output_dir: &Path, category: &str, module_name: &str) -> bool {
    // `output_dir` is `src/modules/<category>/<subdir>` in the common case and
    // `src/modules/<category>` itself in the flat case. The `mod.rs` that owns
    // the module is the parent of the directory the file was written into.
    let Some(parent) = output_dir.parent() else {
        return false;
    };
    let mod_rs = parent.join("mod.rs");
    let Ok(existing) = std::fs::read_to_string(&mod_rs) else {
        return false;
    };
    let decl = format!("pub mod {module_name};");
    if existing.lines().any(|l| l.trim() == decl) {
        return true;
    }
    let mut updated = existing;
    if !updated.ends_with('\n') {
        updated.push('\n');
    }
    updated.push_str(&decl);
    updated.push('\n');
    let write_result = std::fs::write(&mod_rs, updated); // audit-allow: synchronous generator, not on an async runtime
    match write_result {
        Ok(()) => true,
        Err(e) => {
            crate::meprintln!(
                "[!] could not declare '{decl}' in {}: {e}",
                mod_rs.display()
            );
            false
        }
    }
}

/// The default output directory for a category.
pub fn default_output_dir(category: &str) -> PathBuf {
    PathBuf::from("src/modules")
        .join(category)
        .join("translated")
}

/// Options of a template rendered as prompt lines (for reporting).
pub fn describe_options(options: &[TemplateOption]) -> String {
    options
        .iter()
        .map(|o| format!("{}={}", o.name, o.default))
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::frameworks::{Severity, Template};

    fn template() -> Template {
        Template {
            framework: "nuclei".to_string(),
            name: "Demo".to_string(),
            description: "A \"quoted\" description\nwith a newline".to_string(),
            authors: vec!["tester".to_string()],
            references: vec!["https://example.com".to_string()],
            tags: Vec::new(),
            severity: Severity::High,
            disclosure_date: None,
            default_port: Some(8443),
            category: "scanners".to_string(),
            options: Vec::new(),
            protocol: Protocol::None,
            http_based: true,
        }
    }

    #[test]
    fn strings_are_escaped() {
        assert_eq!(rust_string_literal("a\"b"), "\"a\\\"b\""); // audit-allow: test
        assert_eq!(rust_string_literal("a\\b"), "\"a\\\\b\""); // audit-allow: test
        assert_eq!(rust_string_literal("a\nb"), "\"a\\nb\""); // audit-allow: test
    }

    #[test]
    fn raw_strings_survive_quotes() {
        let src = "id: x\ninfo:\n  name: \"quoted\"\n";
        let lit = rust_raw_string_literal(src);
        assert!(lit.starts_with("r#\"")); // audit-allow: test
        assert!(lit.ends_with("\"#")); // audit-allow: test
    }

    #[test]
    fn generated_module_registers_itself() {
        let code = generate(&template(), "scanners", "id: x");
        assert!(code.contains("register_native_module!")); // audit-allow: test
        assert!(code.contains("\"scanners\"") || code.contains("Category::Scanners")); // audit-allow: test
        assert!(!code.contains("let _ =")); // audit-allow: test
    }

    #[test]
    fn option_names_become_identifiers() {
        assert_eq!(rust_ident("RHOSTS"), "rhosts"); // audit-allow: test
        assert_eq!(rust_ident("uri-path"), "uri_path"); // audit-allow: test
        assert_eq!(rust_ident("type"), "type_"); // audit-allow: test
        assert_eq!(rust_ident(""), "option"); // audit-allow: test
    }
}
